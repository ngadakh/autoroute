// Summary aggregates one Harness.Run() over a slice of rows.
type Summary struct {
	N                int            `json:"n"`
	RoutedCost       float64        `json:"routed_cost"`
	BaselineCost     float64        `json:"baseline_cost"`
	RoutedScoreSum   float64        `json:"routed_score_sum"`
	BaselineScoreSum float64        `json:"baseline_score_sum"`
	CheapModelRecall float64        `json:"cheap_model_recall"` // of prompts a cheap model could have handled, the share actually routed cheap - see docs/ARCHITECTURE.md's "What gets measured"
	ByLayer          map[string]int `json:"by_layer"`           // router.LayerL1/L2/... -> row count
	ByTier           map[string]int `json:"by_tier"`            // cheap/mid/frontier -> row count
}

// Accuracy is the mean row score under the router's actual tier choices.
func (s Summary) Accuracy() float64 {
	if s.N == 0 {
		return 0
	}
	return s.RoutedScoreSum / float64(s.N)
}

// BaselineAccuracy is the mean row score an always-frontier router would
// have gotten on the same rows.
func (s Summary) BaselineAccuracy() float64 {
	if s.N == 0 {
		return 0
	}
	return s.BaselineScoreSum / float64(s.N)
}

// CostSavingsPct is how much cheaper routing was than always-frontier.
func (s Summary) CostSavingsPct() float64 {
	if s.BaselineCost == 0 {
		return 0
	}
	return (1 - s.RoutedCost/s.BaselineCost) * 100
}

// WriteResultsMarkdown renders the train/held-out summaries to path. mode
// documents which classifier ran (L1+L2 real ONNX, vs L1-only degraded) —
// that materially changes what the numbers mean, so it goes at the top, not
// buried in a log line nobody reads.
func WriteResultsMarkdown(mode string, train, heldOut Summary, path string) error {
	var b strings.Builder
	b.WriteString("# AutoRoute eval results\n\n")
	b.WriteString("Generated by `make eval` (`cmd/eval`) against RouterBench " +
		"(huggingface.co/datasets/withmartian/routerbench), replayed through " +
		"the same router pipeline internal/proxy uses in production — see " +
		"eval/harness.go. Not fabricated: this is `go run ./cmd/eval` output, " +
		"re-run it yourself with `make eval-setup && make eval`.\n\n")
	fmt.Fprintf(&b, "**Router mode:** %s\n\n", mode)
	b.WriteString("**Tiers:**\n\n| Tier | Model |\n|---|---|\n")
	fmt.Fprintf(&b, "| cheap | `%s` |\n", Tiers[router.TierCheap])
	fmt.Fprintf(&b, "| mid | `%s` |\n", Tiers[router.TierMid])
	fmt.Fprintf(&b, "| frontier | `%s` |\n", Tiers[router.TierFrontier])

	b.WriteString("\n## Results\n\n")
	b.WriteString("| Split | N | Routed cost | Baseline cost (always-frontier) | Savings | Routed accuracy | Baseline accuracy | Cheap-model recall |\n")
	b.WriteString("|---|--:|--:|--:|--:|--:|--:|--:|\n")
	writeRow(&b, "train", train)
	writeRow(&b, "held-out", heldOut)

	b.WriteString("\n## Decisions by tier\n\n")
	b.WriteString("| Split | Tier | Rows |\n|---|---|--:|\n")
	writeCounts(&b, "train", train.ByTier)
	writeCounts(&b, "held-out", heldOut.ByTier)

	b.WriteString("\n## Decisions by layer\n\n")
	b.WriteString("| Split | Layer | Rows |\n|---|---|--:|\n")
	writeCounts(&b, "train", train.ByLayer)
	writeCounts(&b, "held-out", heldOut.ByLayer)

	b.WriteString("\n## What this suggests\n\n")
	b.WriteString(defaultPathNote(heldOut))

	b.WriteString("\n## Honest break-even\n\n")
	fmt.Fprintf(&b, "Routing saved **%.1f%%** of the always-frontier cost on "+
		"the held-out slice, at **%.1f** points of accuracy vs %.1f for "+
		"always-frontier — the price of not calling the frontier model for "+
		"every prompt. Cheap-model recall of **%.1f%%** means that's how "+
		"often, of the prompts a cheap model actually could have answered "+
		"correctly, the router agreed and sent it there.\n\n",
		heldOut.CostSavingsPct(), heldOut.Accuracy()*100, heldOut.BaselineAccuracy()*100,
		heldOut.CheapModelRecall*100)
	b.WriteString("![cost and accuracy chart](RESULTS_chart.svg)\n")

	return os.WriteFile(path, []byte(b.String()), 0o644)
}

func writeRow(b *strings.Builder, name string, s Summary) {
	fmt.Fprintf(b, "| %s | %d | $%.4f | $%.4f | %.1f%% | %.1f%% | %.1f%% | %.1f%% |\n",
		name, s.N, s.RoutedCost, s.BaselineCost, s.CostSavingsPct(),
		s.Accuracy()*100, s.BaselineAccuracy()*100, s.CheapModelRecall*100)
}

// WriteChartSVG hand-rolls a small bar chart (cost and accuracy, router vs
// always-frontier baseline, both splits) as plain SVG — no charting library,
// consistent with the project's minimal-dependencies posture outside the
// cgo/ONNX boundary.
func WriteChartSVG(train, heldOut Summary, path string) error {
	const (
		width, height = 640, 420
		barW, gap     = 50, 30
		chartH        = 140
		costTop       = 50
		accTop        = 260
		labelY        = 20
	)

	type bar struct {
		label string
		value float64 // 0..1 fraction of the group's max
		text  string
	}

	costMax := heldOut.BaselineCost
	if train.BaselineCost > costMax {
		costMax = train.BaselineCost
	}
	frac := func(v, max float64) float64 {
		if max == 0 {
			return 0
		}
		return v / max
	}

	costBars := []bar{
		{"train router", frac(train.RoutedCost, costMax), fmt.Sprintf("$%.3f", train.RoutedCost)},
		{"train baseline", frac(train.BaselineCost, costMax), fmt.Sprintf("$%.3f", train.BaselineCost)},
		{"held-out router", frac(heldOut.RoutedCost, costMax), fmt.Sprintf("$%.3f", heldOut.RoutedCost)},
		{"held-out baseline", frac(heldOut.BaselineCost, costMax), fmt.Sprintf("$%.3f", heldOut.BaselineCost)},
	}
	accBars := []bar{
		{"train router", train.Accuracy(), fmt.Sprintf("%.0f%%", train.Accuracy()*100)},
		{"train baseline", train.BaselineAccuracy(), fmt.Sprintf("%.0f%%", train.BaselineAccuracy()*100)},
		{"held-out router", heldOut.Accuracy(), fmt.Sprintf("%.0f%%", heldOut.Accuracy()*100)},
		{"held-out baseline", heldOut.BaselineAccuracy(), fmt.Sprintf("%.0f%%", heldOut.BaselineAccuracy()*100)},
	}

	var b strings.Builder
	fmt.Fprintf(&b, `<svg xmlns="http://www.w3.org/2000/svg" width="%d" height="%d" viewBox="0 0 %d %d" font-family="sans-serif" font-size="11">`+"\n",
		width, height, width, height)
	b.WriteString(`<rect width="100%" height="100%" fill="white"/>` + "\n")

	drawGroup := func(bars []bar, top int, title string, colorRouter, colorBaseline string) {
		fmt.Fprintf(&b, `<text x="10" y="%d" font-size="14" font-weight="bold">%s</text>`+"\n", top-15, title)
		for i, bar := range bars {
			x := 20 + i*(barW+gap)
			h := int(bar.value * chartH)
			y := top + chartH - h
			color := colorRouter
			if strings.Contains(bar.label, "baseline") {
				color = colorBaseline
			}
			fmt.Fprintf(&b, `<rect x="%d" y="%d" width="%d" height="%d" fill="%s"/>`+"\n", x, y, barW, h, color)
			fmt.Fprintf(&b, `<text x="%d" y="%d" text-anchor="middle">%s</text>`+"\n", x+barW/2, y-4, bar.text)
			fmt.Fprintf(&b, `<text x="%d" y="%d" text-anchor="middle" font-size="9">%s</text>`+"\n",
				x+barW/2, top+chartH+14, bar.label)
		}
	}

	fmt.Fprintf(&b, `<text x="10" y="%d" font-size="16" font-weight="bold">AutoRoute eval — cost &amp; accuracy vs always-frontier</text>`+"\n", labelY)
	drawGroup(costBars, costTop, "Cost (USD, total over split)", "#2563eb", "#94a3b8")
	drawGroup(accBars, accTop, "Accuracy (mean row score)", "#16a34a", "#94a3b8")
	b.WriteString(`</svg>` + "\n")

	return os.WriteFile(path, []byte(b.String()), 0o644)
}

// defaultPathNote reads a split's layer breakdown and says, honestly, how
// much of the traffic the router actually decided with confidence (L1, or
// L2 above theta_high) versus how much fell to the conservative default
// tier — a low L1 rate plus a high conservative-default rate on a given
// benchmark distribution means the L1 rules and L2 exemplars (authored for
// general assistant chat in M0-M2, not this benchmark) don't confidently
// discriminate that traffic, not that the harness is broken.
func defaultPathNote(s Summary) string {
	if s.N == 0 {
		return "No rows in this split.\n"
	}
	l1 := s.ByLayer[router.LayerL1]
	conservative := s.ByLayer[router.LayerL2BandDefault] + s.ByLayer[router.LayerDegradedLowConf] + s.ByLayer[router.LayerDegradedNoL2]
	l1Pct := float64(l1) / float64(s.N) * 100
	conservativePct := float64(conservative) / float64(s.N) * 100

	if l1Pct < 5 && conservativePct > 50 {
		return fmt.Sprintf("L1 heuristics decided only **%.1f%%** of held-out rows, and "+
			"**%.1f%%** landed in the conservative-default path (L2 confidence below "+
			"`theta_low`, or L2 unavailable) rather than a confident tier decision. "+
			"That's the L1 rules and L2 exemplars — authored for general assistant chat "+
			"in M0-M2 — not confidently discriminating this benchmark's academic-exam-style "+
			"prompts (MMLU, GSM8K, Winogrande, ...), not a bug in the harness. It's exactly "+
			"the failure mode `docs/ARCHITECTURE.md` calls out: \"the uncertain middle band "+
			"always resolves to the conservative default — the router fails toward quality.\" "+
			"Expanding the L2 route taxonomy to cover benchmark-style traffic is future work, "+
			"not this milestone's.\n", l1Pct, conservativePct)
	}
	return fmt.Sprintf("L1 heuristics decided **%.1f%%** of held-out rows; only **%.1f%%** "+
		"fell to the conservative-default path (L2 confidence below `theta_low`, or L2 "+
		"unavailable) — the router made a confident tier decision for most traffic on this "+
		"benchmark.\n", l1Pct, conservativePct)
}

func writeCounts(b *strings.Builder, name string, counts map[string]int) {
	keys := make([]string, 0, len(counts))
	for k := range counts {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	for _, k := range keys {
		fmt.Fprintf(b, "| %s | %s | %d |\n", name, k, counts[k])
	}
}
